use super::{BoxCell, dash_ends, mask};

fn shade(alpha: u8) -> char {
    match alpha {
        0 => '.',
        1..=63 => '-',
        64..=191 => '+',
        _ => '#',
    }
}

fn art(chars: &str, cell: &BoxCell) -> String {
    let masks: Vec<_> = chars.chars().map(|c| mask(c, cell).unwrap()).collect();
    (0..usize::from(cell.height))
        .map(|row| {
            let cells = masks
                .iter()
                .map(|drawn| drawn.rows().nth(row).unwrap().iter().map(|&alpha| shade(alpha)).collect::<String>());
            cells.collect::<Vec<_>>().join(" ")
        })
        .collect::<Vec<_>>()
        .join("\n")
}

const CELL: BoxCell = BoxCell { width: 7, height: 10, scale: 1 };
const DOUBLED: BoxCell = BoxCell { width: 11, height: 14, scale: 2 };
const WIDE: BoxCell = BoxCell { width: 12, height: 6, scale: 1 };

#[test]
fn only_box_drawing_and_block_characters_have_a_drawn_mask() {
    let drawn = |c| mask(c, &CELL).map(|found| (found.left, found.top, found.width, found.height, found.alpha.len()));
    assert_eq!(
        [drawn('a'), drawn('\u{24ff}'), drawn('\u{25a0}'), drawn('─')],
        [None, None, None, Some((0, 0, 7, 10, 70))]
    );
}

#[test]
fn dashes_split_the_length_evenly_with_a_gap_of_a_third_of_a_step() {
    let ends = |length, count| dash_ends(length, count).collect::<Vec<_>>();
    assert_eq!(ends(10.0, 3), [(1.0, 3.0), (4.0, 6.0), (7.0, 10.0)]);
    assert_eq!(ends(12.0, 4), [(1.0, 3.0), (4.0, 6.0), (7.0, 9.0), (10.0, 12.0)]);
    assert_eq!(ends(4.0, 4), [(1.0, 1.0), (2.0, 2.0), (3.0, 3.0), (4.0, 4.0)]);
}

